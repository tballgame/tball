test('catalog preserves legacy results, isolates each event, and hides drafts', () => {
  const owner = { uid: 'owner', organizer: true };
  const member = { uid: 'member', organizer: false };
  const today = '2026-11-06';
  const details = { title: '新賽事', signupDeadline: today, deadline: '2026-12-01', teamSize: '2' };
  const state = mutate(null, owner, { ...details, title: '舊賽事', action: 'publish' }, today);
  state.members.push({ id: member.uid, name: '會員' });
  state.event.players.push({ id: 'p1', uid: member.uid, name: '會員' });
  state.event.phase = 'locked';
  state.event.teams = [{ id: 't1', name: '甲隊' }, { id: 't2', name: '乙隊' }];
  state.tournament = { teams: state.event.teams, fixtures: [{ id: 'old', teams: ['t1', 't2'], lineups: {},
    points: [{ format: 1, result: { status: 'confirmed', score: [3, 1] } }] }] };
  assert.equal(migrateCatalog(state), true);
  assert.equal(migrateCatalog(state), false);
  assert.equal(catalogView(state, owner).events[0].archived, true);
  assert.equal(catalogView(state, owner).events[0].number, 1);
  assert.deepEqual(catalogView(state, owner).events[0].leaders, ['甲隊']);
  assert.deepEqual(catalogView(state, owner, 'legacy').matchups[0].points[0].result.score, [3, 1]);
  assert.deepEqual(catalogView(state, { uid: 'spectator', organizer: false }, 'legacy').standings.map(team => team.name), ['甲隊', '乙隊']);
  const draft = changeCatalog(state, owner, { ...details, action: 'createDraft' }, today);
  const active = changeCatalog(state, owner, { ...details, title: '另一場', action: 'publish' }, today);
  assert.throws(() => catalogView(state, member, draft));
  assert.equal(catalogView(state, member).events.length, 2);
  changeCatalog(state, owner, { action: 'publishDraft', eventId: draft }, today);
  changeCatalog(state, member, { action: 'register', eventId: draft, name: '會員' }, today);
  changeCatalog(state, owner, { action: 'captain', eventId: draft, player: 'p1', name: '丙隊' }, today);
  assert.equal(catalogView(state, owner, draft).teams[0].captainId, 'p1');
  assert.equal(catalogView(state, owner, draft).players.length, 1);
  assert.equal(catalogView(state, owner, active).players.length, 0);
  changeCatalog(state, member, { action: 'register', eventId: active, name: '另一場的名字' }, today);
  assert.equal(catalogView(state, owner, draft).players[0].name, '會員');
  assert.equal(catalogView(state, owner, active).players[0].name, '另一場的名字');
  const memberEvents = catalogView(state, member).events;
  assert.deepEqual(memberEvents.find(event => event.id === draft).captain, { teamName: '丙隊', playerName: '會員' });
  assert.equal(memberEvents.find(event => event.id === active).captain, undefined);
  assert.ok(catalogView(state, { uid: null, organizer: false }).events.every(event => !event.captain));
  changeCatalog(state, owner, { action: 'captain', eventId: active, player: 'p1', name: '丁隊' }, today);
  assert.deepEqual(catalogView(state, member).events.filter(event => event.captain).map(event => event.captain), [
    { teamName: '丙隊', playerName: '會員' }, { teamName: '丁隊', playerName: '另一場的名字' }
  ]);
  assert.equal(catalogView(state, owner).members[0].history.length, 3);
  assert.equal(catalogView(state, owner).events.find(event => event.id === draft).openedOn, today);
  changeCatalog(state, owner, { action: 'addMember', name: '新增名冊會員' }, today);
  const added = catalogView(state, owner).members.find(item => item.name === '新增名冊會員');
  assert.ok(added);
  changeCatalog(state, owner, { action: 'removeMember', memberId: added.id }, today);
  assert.equal(catalogView(state, owner).members.some(item => item.id === added.id), false);
  const noDeadline = changeCatalog(state, owner, { ...details, action: 'publish', deadline: '', teamSize: '', matchFormat: '11122' }, today);
  assert.equal(catalogView(state, owner, noDeadline).event.teamSize, 7);
  assert.equal(catalogView(state, owner, noDeadline).event.deadline, '');
  assert.throws(() => changeCatalog(state, owner, { action: 'archive', eventId: active }, today));

  const deleteArchivedEvent = { action: 'deleteArchivedEvent', eventId: 'legacy' };
  assert.throws(() => changeCatalog(state, member, deleteArchivedEvent, today), /僅限大會/);
  assert.throws(() => changeCatalog(state, owner, { ...deleteArchivedEvent, eventId: active }, today), /只能刪除/);
  assert.equal(changeCatalog(state, owner, deleteArchivedEvent, today), null);
  assert.throws(() => catalogView(state, member, 'legacy'), /找不到/);
  assert.throws(() => changeCatalog(state, owner, deleteArchivedEvent, today), /找不到/);
  assert.deepEqual(catalogView(state, member).events.map(event => event.number), [2, 3, 4]);
  assert.equal(catalogView(state, owner, active).eventNumber, 3);
  assert.deepEqual(catalogView(state, owner).members[0].history.map(event => event.id), [draft, active]);
  const next = changeCatalog(state, owner, { ...details, action: 'createDraft' }, today);
  assert.equal(catalogView(state, owner, next).eventNumber, 5);
});

test('30 demo members enter the roster without becoming participants', () => {
  const owner = { uid: 'owner', organizer: true };
  const guest = { uid: 'guest', organizer: false };
  const today = '2026-11-06';
  const state = mutate(null, owner, {
    action: 'publish', title: '測試賽', signupDeadline: today, deadline: '2026-12-01', teamSize: 3
  }, today);
  assert.throws(() => mutate(state, guest, { action: 'seedPlayers' }, today));
  mutate(state, owner, { action: 'seedPlayers' }, today);
  assert.equal(view(state, owner).memberCount, 30);
  assert.equal(view(state, owner).players.length, 0);
  const [first, second] = view(state, owner).unenrolledMembers;
  mutate(state, owner, { action: 'enrollMembers', members: [first.id, second.id] }, today);
  assert.equal(view(state, owner).players.length, 2);
  assert.equal(view(state, owner).unenrolledMembers.length, 28);
  assert.throws(() => mutate(state, owner, { action: 'enrollMembers', members: [first.id] }, today));
  assert.equal(view(state, guest).player, null);
  assert.throws(() => mutate(state, owner, { action: 'seedPlayers' }, today));
});

test('catalog counts legacy submissions without waiting for confirmation', () => {
  const pending = { score: [2, 3], side: 0, player: 'p1', status: 'pending' };
  const disputed = { score: [1, 3], side: 0, status: 'disputed' };
  const tournament = { fixtures: [{ points: [{ result: pending }, { result: disputed }] }] };
  const state = { events: [{ number: 2, tournament }], nextEventNumber: 3 };
  assert.equal(migrateCatalog(state), true);
  assert.deepEqual(pending, { score: [2, 3], side: 0, player: 'p1', status: 'confirmed' });
  assert.equal(disputed.status, 'disputed');
  assert.equal(state.events[0].number, 2);
  assert.equal(migrateCatalog(state), false);
});

test('an organizer can register and complete only their own team as captain', () => {
  const owner = { uid: 'owner', organizer: true };
  const member = { uid: 'member', organizer: false };
  const otherCaptain = { uid: 'other', organizer: false };
  const today = '2026-11-06';
  const state = mutate(null, owner, {
    action: 'publish', title: '雙重身分測試', signupDeadline: today, teamSize: 2
  }, today);
  const act = (actor, data) => {
    const updated = mutate(state, actor, data, today);
    state.event = updated.event;
  };
  act(owner, { action: 'register', name: '主辦選手' });
  assert.throws(() => act(owner, { action: 'register', name: '再次報名' }));
  act(member, { action: 'register', name: '選手甲' });
  act(otherCaptain, { action: 'register', name: '選手乙' });
  act(owner, { action: 'captain', player: 'p1', name: '甲隊' });
  act(owner, { action: 'captain', player: 'p3', name: '乙隊' });
  assert.equal(view(state, owner).team.captainId, 'p1');
  assert.throws(() => act(owner, { action: 'completeTeam' }), /最低人數/);
  act(owner, { action: 'add', players: ['p2'] });
  act(owner, { action: 'completeTeam', teamId: 't2' });
  assert.equal(view(state, owner).team.rosterComplete, true);
  assert.equal(view(state, otherCaptain).team.rosterComplete, undefined);

  const replace = { action: 'replaceCaptain', team: 't1', player: 'p2' };
  assert.throws(() => act(member, replace), /僅限大會/);
  assert.throws(() => act(owner, { ...replace, player: 'p3' }), /本隊隊員或尚未入隊/);
  act(owner, replace);
  assert.deepEqual(view(state, member).team.playerIds, ['p1', 'p2']);
  assert.equal(view(state, member).team.captainId, 'p2');
  assert.equal(view(state, member).team.rosterComplete, undefined);
  assert.throws(() => act(owner, { action: 'completeTeam' }), /只有隊長/);
  act(member, { action: 'completeTeam' });
  assert.equal(view(state, owner).team.rosterComplete, true);

  const freeMember = { uid: 'free', organizer: false };
  act(freeMember, { action: 'register', name: '選手丙' });
  act(owner, { ...replace, player: 'p4' });
  assert.deepEqual(view(state, freeMember).team.playerIds, ['p1', 'p2', 'p4']);
  assert.equal(view(state, freeMember).team.captainId, 'p4');
  act(member, { action: 'leave' });
  assert.throws(() => act(owner, replace), /無法加入/);
  state.event.phase = 'locked';
  assert.throws(() => act(owner, { ...replace, player: 'p1' }), /沒有開放操作/);
});

test('cloud permissions and identity derive from the authenticated account', () => {
  const owner = { uid: 'owner-uid', organizer: true };
  const guests = ['alpha', 'beta', 'gamma', 'delta'].map(uid => ({ uid, organizer: false }));
  const [captain, member, otherCaptain, otherMember] = guests;
  const publicActor = { uid: null, organizer: false };
  const today = '2026-11-06';
  const publish = { action: 'publish', title: '循環賽', signupDeadline: today, deadline: '2026-12-01',
    teamSize: '2', matchFormat: '22121' };
  assert.throws(() => mutate(null, publicActor, publish, today));
  assert.throws(() => mutate(null, captain, { ...publish, organizer: true }, today));
  assert.throws(() => mutate(null, owner, { ...publish, matchFormat: 'unknown' }, today));
  const state = mutate(null, owner, publish, today);
  assert.equal(view(state, publicActor).event.matchFormat, publish.matchFormat);
  const act = (actor, data) => mutate(state, actor, data, today);
  const registeredNames = ['選手甲', '選手乙', '選手丙', '選手乙'];
  const registeredPlayers = guests.map((actor, index) => {
    const memberNumber = 'M000' + (index + 1);
    state.members.push({ id: actor.uid, number: memberNumber, name: '會員 ' + memberNumber });
    return { name: registeredNames[index], memberNumber };
  });
  guests.slice(0, 3).forEach((actor, index) => act(actor, { action: 'register', name: registeredNames[index] }));
  assert.throws(() => act(owner, { action: 'enrollMembers', members: [captain.uid] }), /尚未報名/);
  assert.throws(() => act(otherMember, { action: 'enrollMembers', members: [otherMember.uid] }), /僅限大會/);
  act(owner, { action: 'enrollMembers', members: [otherMember.uid], names: [registeredNames[3]] });
  assert.equal(view(state, otherMember).player.name, registeredNames[3]);
  assert.throws(() => act(member, { action: 'register', name: '第二次報名', uid: 'fake' }));
  assert.equal(view(state, publicActor).players, undefined);
  assert.equal(view(state, publicActor).registeredPlayers, undefined);
  const spectator = { uid: 'spectator', organizer: false };
  const spectatorView = view(state, spectator);
  assert.deepEqual(spectatorView.registeredPlayers, registeredPlayers);
  assert.equal(spectatorView.players, undefined);
  assert.deepEqual(view(state, owner).registeredPlayers, registeredPlayers);
  assert.equal(view(state, owner).players[0].uid, undefined);
  assert.throws(() => act(captain, { action: 'captain', player: 'p1', name: 'A' }));
  act(owner, { action: 'captain', player: 'p1', name: 'A' });
  act(owner, { action: 'captain', player: 'p3', name: 'B' });
  assert.equal(view(state, captain).event.phase, 'signup');
  assert.equal(view(state, captain).eligible.find(player => player.id === 'p2').assigned, false);
  assert.throws(() => act(captain, { action: 'completeTeam' }), /最低人數/);
  assert.throws(() => act(owner, { action: 'completeTeam' }), /只有隊長/);
  assert.throws(() => act(captain, { action: 'add', players: ['p2', 'p99'] }));
  assert.deepEqual(view(state, captain).team.playerIds, ['p1']);
  act(captain, { action: 'add', players: ['p2'] });
  assert.throws(() => act(member, { action: 'completeTeam' }), /只有隊長/);
  act(captain, { action: 'completeTeam' });
  assert.equal(view(state, captain).team.rosterComplete, true);
  assert.equal(view(state, owner).teams[0].rosterComplete, true);
  assert.deepEqual(view(state, member).registeredPlayers, registeredPlayers);
  assert.equal(view(state, otherCaptain).eligible.find(player => player.id === 'p2').assigned, true);
  assert.throws(() => act(otherCaptain, { action: 'add', player: 'p2' }));
  assert.throws(() => act(otherCaptain, { action: 'remove', player: 'p2' }));
  assert.throws(() => act(captain, { action: 'remove', player: 'p1' }));
  act(captain, { action: 'remove', player: 'p2' });
  assert.equal(view(state, owner).teams[0].rosterComplete, undefined);
  assert.equal(view(state, member).team, null);
  assert.equal(view(state, member).player.id, 'p2');
  act(captain, { action: 'add', players: ['p2'] });
  act(otherCaptain, { action: 'add', player: 'p4' });
  assert.throws(() => act(otherMember, { action: 'add', player: 'p2', uid: captain.uid }));
  act(otherMember, { action: 'leave', player: 'p2' });
  assert.equal(view(state, member).team.name, 'A');
  act(captain, { action: 'completeTeam' });
  act(member, { action: 'leave' });
  assert.equal(view(state, owner).teams[0].rosterComplete, undefined);
  assert.equal(view(state, member).team, null);
  assert.equal(view(state, member).player.name, registeredNames[1]);
  assert.throws(() => act(captain, { action: 'add', player: 'p2' }));
  assert.throws(() => act(otherMember, { action: 'allow', team: 't1', player: 'p2' }));
  assert.equal(view(state, captain).eligible.some(player => player.id === 'p2'), false);
  act(member, { action: 'allow', team: 't1' });
  act(captain, { action: 'add', player: 'p2' });
  act(otherMember, { action: 'allow', team: 't2' });
  const assign = { action: 'addTeamMembers', assignments: [{ teamId: 't2', players: ['p4'] }] };
  assert.throws(() => act(otherCaptain, assign), /僅限大會/);
  assert.throws(() => act(owner, { ...assign, assignments: [...assign.assignments, { teamId: 't1', players: ['p4'] }] }));
  assert.equal(view(state, otherMember).team, null);
  act(owner, assign);
  assert.equal(view(state, otherMember).team.name, 'B');
  assert.equal(view(state, otherCaptain).team.rosterComplete, undefined);
  assert.equal(view(state, owner).fixturePreview, undefined);
  act(captain, { action: 'completeTeam' });
  act(otherCaptain, { action: 'completeTeam' });
  const preview = view(state, owner).fixturePreview;
  assert.deepEqual(preview, [['A', 'B']]);
  assert.deepEqual(view(state, captain).fixturePreview, preview);
  assert.equal(view(state, member).fixturePreview, undefined);
  assert.equal(state.event.phase, 'signup');
  assert.equal(state.tournament, undefined);
  assert.throws(() => act(captain, { action: 'lock' }));
  assert.throws(() => act(owner, { action: 'lock' }));
  act(owner, { action: 'close' });
  assert.deepEqual(view(state, owner).fixturePreview, preview);
  act(owner, { action: 'lock' });
  assert.equal(view(state, captain).eligible, undefined);
  assert.equal(view(state, owner).fixturePreview, undefined);
  assert.deepEqual(view(state, member).fixtures, preview);
  assert.deepEqual(state.tournament.fixtures[0].points.map(point => point.format), [2, 2, 1, 2, 1]);
  const lineup = { action: 'lineup', fixture: 't1-t2', starters: ['p1', 'p2', 'p1', 'p2', 'p2', 'p1', 'p2', 'p2'] };
  assert.throws(() => act(member, lineup));
  assert.throws(() => act(captain, { ...lineup, starters: ['p1', 'p1', ...lineup.starters.slice(2)] }));
  act(captain, lineup);
  assert.deepEqual(view(state, captain).lineups[0].starters[0], ['p1', 'p2']);
  assert.deepEqual(view(state, otherCaptain).lineups[0].starters, []);
  assert.deepEqual(view(state, otherCaptain).matchups[0].points[0].sides, [[], []]);
  assert.deepEqual(view(state, spectator).matchups[0].points[0].sides, [[], []]);
  assert.deepEqual(view(state, owner).matchups[0].submitted, [true, false]);
  assert.deepEqual(view(state, owner).matchups[0].points[0].sides, [registeredNames.slice(0, 2), []]);
  act(otherCaptain, { ...lineup, starters: lineup.starters.map(id => id === 'p1' ? 'p3' : 'p4') });
  assert.deepEqual(view(state, owner).matchups[0].points[0].sides, [registeredNames.slice(0, 2), registeredNames.slice(2)]);
  for (const actor of [captain, member, spectator]) {
    assert.deepEqual(view(state, actor).matchups[0].points[0].sides, [registeredNames.slice(0, 2), registeredNames.slice(2)]);
  }
  assert.equal(view(state, spectator).matchups[0].points[0].canScore, false);
  const publicBoard = view(state, publicActor);
  assert.deepEqual(publicBoard.matchups[0].teams, ['A', 'B']);
  assert.deepEqual(publicBoard.matchups[0].points[0].sides, [[], []]);
  assert.equal(publicBoard.matchups[0].points[0].canScore, false);
  assert.equal(publicBoard.matchups[0].points[0].canDispute, false);
  assert.equal(publicBoard.registeredPlayers, undefined);
  const score = { action: 'score', fixture: lineup.fixture, point: '0', home: '2', away: '3' };
  assert.throws(() => act(owner, { ...score, home: '' }));
  act(member, score);
  assert.equal(view(state, owner).matchups[0].points[0].result.status, 'confirmed');
  assert.deepEqual(view(state, owner).matchups[0].summary, { wins: [0, 1], complete: false });
  assert.equal(view(state, otherCaptain).matchups[0].points[0].canDispute, true);
  assert.equal(view(state, captain).matchups[0].points[0].canDispute, false);
  assert.throws(() => act(captain, { ...score, action: 'disputeScore' }));
  act(otherCaptain, { ...score, action: 'disputeScore' });
  assert.equal(view(state, owner).matchups[0].points[0].result.status, 'disputed');
  assert.deepEqual(view(state, owner).matchups[0].points[0].dispute, { team: 'B', player: registeredNames[2] });
  assert.deepEqual(view(state, owner).matchups[0].summary, { wins: [0, 0], complete: false });
  assert.throws(() => act(otherMember, { ...score, action: 'disputeScore' }));
  act(owner, score);
  assert.deepEqual(view(state, owner).matchups[0].points[0].result, { score: [2, 3], status: 'confirmed' });
  assert.equal(view(state, otherCaptain).matchups[0].points[0].canDispute, false);
  assert.equal(view(state, owner).matchups[0].points[0].canScore, true);
  assert.throws(() => act(member, score));
  act(member, { ...score, point: '1', home: '3', away: '2' });
  assert.equal(view(state, owner).matchups[0].points[1].result.status, 'confirmed');
  assert.equal(view(state, owner).standings[0].won, 0);
  const captainScore = { ...score, point: '2', home: '1', away: '3' };
  const captainPoint = view(state, captain).matchups[0].points[2];
  assert.deepEqual(captainPoint.sides, [[registeredNames[1]], [registeredNames[3]]]);
  assert.equal(captainPoint.canScore, true);
  assert.throws(() => act({ uid: 'spectator', organizer: false }, captainScore));
  act(captain, captainScore);
  assert.equal(view(state, otherCaptain).matchups[0].points[2].canDispute, true);
  assert.throws(() => act(member, { ...captainScore, action: 'disputeScore' }));
  assert.throws(() => act({ uid: 'spectator', organizer: false }, { ...captainScore, action: 'disputeScore' }));
  for (const point of ['3', '4']) act(owner, { ...score, point, home: '1', away: '3' });
  assert.deepEqual(view(state, owner).matchups[0].summary, { wins: [1, 4], complete: true });
  assert.deepEqual(view(state, owner).standings.map(({ name, won, points }) => [name, won, points]),
    [['B', 1, 4], ['A', 0, 1]]);
  act(otherMember, { ...captainScore, action: 'disputeScore' });
  assert.deepEqual(view(state, owner).matchups[0].summary, { wins: [1, 3], complete: false });
  assert.equal(view(state, owner).standings[0].won, 0);
  act(owner, captainScore);
  act(owner, { ...score, point: '0', home: '3', away: '2' });
  act(owner, { ...score, point: '4', home: '3', away: '1' });
  assert.deepEqual(view(state, owner).matchups[0].summary, { wins: [3, 2], complete: true });
  assert.deepEqual(view(state, owner).standings.map(({ name, won, points }) => [name, won, points]),
    [['A', 1, 3], ['B', 0, 2]]);
  assert.throws(() => act(member, { action: 'leave' }));
});
